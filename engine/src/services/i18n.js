const mergeDeep = (target, source) => {
  Object.entries(source || {}).forEach(([key, value]) => {
    if (value && typeof value === "object" && !Array.isArray(value)) {
      target[key] = mergeDeep({ ...(target[key] || {}) }, value);
      return;
    }
    target[key] = value;
  });
  return target;
};

